/** Bounding box (lon/lat) covering the mainland and both island groups. */
export const INDIA_BOUNDS = { minLon: 68.0, maxLon: 97.5, minLat: 6.5, maxLat: 37.2 };

/** A conceptual highlight location (roughly central India). Not a real GI location. */
export const CONCEPTUAL_MARKER: LonLat = [78.0, 22.5];

/**
 * Projects a lon/lat point into a unit square centred at the origin, x → east, y → north,
 * preserving aspect (1° lon ≈ 0.9° lat at India's latitude).
 */
export function toUnit([lon, lat]: LonLat): LonLat {
  const { minLon, maxLon, minLat, maxLat } = INDIA_BOUNDS;
  const w = (maxLon - minLon) * 0.9;
  const h = maxLat - minLat;
  const scale = 1 / Math.max(w, h);
  const cx = (minLon + maxLon) / 2;
  const cy = (minLat + maxLat) / 2;
  return [(lon - cx) * 0.9 * scale, (lat - cy) * scale];
}

/** The mainland ring in unit coordinates. */
export function indiaUnitPolygon(): LonLat[] {
  return INDIA_OUTLINE.map(toUnit);
}

/** Every drawable ring (mainland first, then the larger Andaman & Nicobar islands) in unit coordinates. */
export function indiaUnitRings(): LonLat[][] {
  return [INDIA_OUTLINE, ...ANDAMAN_NICOBAR_RINGS].map((ring) => ring.map(toUnit));
}

/** Island dots in unit coordinates. */
export function indiaUnitDots(): LonLat[] {
  return [...ANDAMAN_NICOBAR_DOTS, ...LAKSHADWEEP_DOTS].map(toUnit);
}

/**
 * SVG path data for the whole map in a viewBox of `size` × `size` (y down), with the
 * unit polygon scaled by `scale` and centred. Dots are emitted as tiny circles (as arcs).
 */
export function indiaSvgPath(size = 1000, scale = 0.92): string {
  const half = size / 2;
  const s = size * scale;
  const pt = ([x, y]: LonLat) => `${(half + x * s).toFixed(1)} ${(half - y * s).toFixed(1)}`;
  const rings = indiaUnitRings().map((ring) => `M${ring.map(pt).join("L")}Z`);
  const r = Math.max(1.2, size * 0.0028);
  const dots = indiaUnitDots().map(([x, y]) => {
    const cx = half + x * s;
    const cy = half - y * s;
    return `M${(cx - r).toFixed(1)} ${cy.toFixed(1)}a${r} ${r} 0 1 0 ${(r * 2).toFixed(1)} 0a${r} ${r} 0 1 0 -${(r * 2).toFixed(1)} 0Z`;
  });
  return [...rings, ...dots].join(" ");
}
